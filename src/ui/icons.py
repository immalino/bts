def render_svg_pixmap(name: str, color: str = "#64748B", size: int = 16) -> QPixmap:
    """
    Me-render SVG monokrom menjadi QPixmap berkualitas tinggi dengan warna dan ukuran tertentu.
    
    Args:
        name: Nama ikon terdaftar di SVG_ICONS.
        color: Kode warna CSS hex (misal '#2563EB').
        size: Dimensi piksel (lebar dan tinggi).
        
    Returns:
        QPixmap yang sudah di-render secara tajam.
    """
    svg_template = SVG_ICONS.get(name)
    if not svg_template:
        pixmap = QPixmap(size, size)
        pixmap.fill(Qt.GlobalColor.transparent)
        return pixmap

    svg_content = svg_template.format(color=color).encode("utf-8")
    byte_array = QByteArray(svg_content)
    renderer = QSvgRenderer(byte_array)

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    renderer.render(painter)
    painter.end()

    return pixmap


def get_icon(name: str, color: Optional[str] = None, size: int = 16) -> QIcon:
    """
    Membuat QIcon dari ikon vektor SVG dengan dukungan high-DPI.
    
    Args:
        name: Nama ikon terdaftar di SVG_ICONS.
        color: Warna default ikon (jika None, menggunakan slate-500 '#64748B').
        size: Ukuran render dasar.
        
    Returns:
        QIcon modern yang tajam.
    """
    fill_color = color or "#64748B"
    # Render di resolusi standar dan 2x untuk tampilan high-DPI (Retina)
    pm1 = render_svg_pixmap(name, color=fill_color, size=size)
    pm2 = render_svg_pixmap(name, color=fill_color, size=size * 2)

    icon = QIcon()
    icon.addPixmap(pm1)
    icon.addPixmap(pm2)
    return icon

